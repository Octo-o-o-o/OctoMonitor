export type I18nKey = keyof typeof en

const locales: Record<Locale, Record<I18nKey, string>> = { en, zh }

interface I18nContextValue {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (key: I18nKey) => string
}

const I18nContext = createContext<I18nContextValue>({
  locale: 'en',
  setLocale: () => {},
  t: (key) => key,
})

function getInitialLocale(): Locale {
  const stored = localStorage.getItem('octomonitor-locale')
  if (stored === 'en' || stored === 'zh') return stored
  const browserLang = navigator.language.toLowerCase()
  return browserLang.startsWith('zh') ? 'zh' : 'en'
}

export function I18nProvider({ children }: PropsWithChildren) {
  const [locale, setLocaleState] = useState<Locale>(getInitialLocale)

  const setLocale = useCallback((l: Locale) => {
    localStorage.setItem('octomonitor-locale', l)
    setLocaleState(l)
  }, [])

  const t = useCallback((key: I18nKey) => locales[locale][key] ?? key, [locale])

  return <I18nContext.Provider value={{ locale, setLocale, t }}>{children}</I18nContext.Provider>
}

export function useI18n() {
  return useContext(I18nContext)
}
